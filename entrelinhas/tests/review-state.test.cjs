const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../static/review-state.js'), 'utf8');
const rules = vm.runInNewContext(source + '\nReviewRules;');
const image = {id:'image',rule:'alt_quality',action:'alt',quick_image:true,severity:'review',page:0,block_id:'img0'};
const missing = {...image,id:'missing',rule:'alt_missing'};
const font = {id:'font',rule:'font_size',action:'font',page:0};
const analysis = {issues:[image,font],pages:[{}],resolved_by_edit:['image']};
const restored = rules.restore(analysis,{resolved:[],filters:{category:'all',status:'pending'},issue_id:'image'});
assert.equal(restored.resolved.has('image'),true);
assert.equal(restored.selected,1);
assert.equal(rules.canResolve(image),true);
assert.equal(rules.canResolve(missing),false);
assert.equal(rules.canResolve(font),false);
assert.equal(rules.sameTarget(missing,image),true);
assert.equal(rules.sameTarget(missing,{...image,block_id:'img1'}),false);
assert.equal(rules.sameTarget(image,font),false);
assert.deepEqual(Array.from(rules.indexes(analysis.issues,{category:'all',status:'pending'},restored.resolved)),[1]);
const manual = rules.restore({...analysis,resolved_by_edit:[]},{resolved:['image'],issue_id:'font'});
assert.equal(manual.resolved.has('image'),true);
assert.equal(manual.selected,1);
console.log('Review restoration and image navigation passed.');
